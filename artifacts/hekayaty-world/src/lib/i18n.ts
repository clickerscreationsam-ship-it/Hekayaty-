type TranslationObj = typeof ar;

function resolvePath(obj: Record<string, unknown>, path: string): string {
  const parts = path.split('.');
  let current: unknown = obj;
  for (const part of parts) {
    if (current == null || typeof current !== 'object') return path;
    current = (current as Record<string, unknown>)[part];
  }
  if (typeof current === 'string') return current;
  return path;
}

let _currentLanguage: 'ar' | 'en' = 'ar';

export function setLanguage(lang: 'ar' | 'en'): void {
  _currentLanguage = lang;
}

export function t(key: string, lang?: 'ar' | 'en'): string {
  const language = lang ?? _currentLanguage;
  const translations: Record<string, unknown> =
    language === 'en' ? (en as unknown as Record<string, unknown>) : (ar as unknown as Record<string, unknown>);
  return resolvePath(translations, key);
}

export function useTranslation(): {
  t: (key: string) => string;
  language: 'ar' | 'en';
  dir: 'rtl' | 'ltr';
} {
  // Read from store when available, otherwise fall back to module-level language
  let language: 'ar' | 'en' = 'ar';
  try {
    language = useAppStore.getState().language ?? 'ar';
  } catch {
    language = _currentLanguage;
  }

  const dir: 'rtl' | 'ltr' = language === 'ar' ? 'rtl' : 'ltr';

  return {
    t: (key: string) => t(key, language),
    language,
    dir,
  };
}

export type { TranslationObj };
